/**
 * Returns the rental yield per point for a resort at a given season.
 * yield = market rental rate / point cost for that season
 */
export function getYieldPerPoint(resort: MVCResort, season: 'low' | 'avg' | 'peak'): number {
  const rateKey = season
  const ptsKey = season === 'avg' ? 'mid' : season
  return resort.marketRates[rateKey] / resort.pointCosts[ptsKey]
}

/**
 * Returns all resorts sorted by $/pt yield descending for the given season.
 * Defaults to 'peak' if no season specified.
 */
export function getRankedByYield(season: 'low' | 'avg' | 'peak' = 'peak'): MVCResort[] {
  return [...resorts].sort((a, b) => getYieldPerPoint(b, season) - getYieldPerPoint(a, season))
}
